#!/usr/bin/env node
/*
 * Purchase + batch-tracking integration tests. Run with:
 *   node server/scripts/test-batch-purchase.js
 *
 * Exits 0 on full pass, 1 on any failure. Uses live PG (same DB as
 * the running server). All fixtures get the prefix _TBP_
 * so cleanup can target them safely without disturbing real data.
 *
 * What the suite covers:
 *   B-CREATE-1  Reject purchase of batch-tracked product without batch number
 *   B-CREATE-2  New batch number → product_batches row + product_batch_stock row + stock_ledger.batch_id
 *   B-CREATE-3  Existing batch number → no duplicate, stock adds to the same batch
 *   B-CREATE-4  Same batch number on two products → both allowed (uniqueness is per product)
 *   B-CANCEL    Cancelling a batch purchase reverses product_batch_stock + drops the ledger row
 *   B-DISABLED  With global batch_tracking_enabled=false, batch field is silently ignored
 *
 * Tests interact with the controller layer (not raw HTTP) by constructing
 * mock req/res objects — same approach the other phaseN test scripts use.
 */

require('dotenv').config({ path: require('path').join(__dirname, '..', '..', '.env') });

const {
  sequelize, Party, Product, Category, Godown, SystemSettings,
  PurchaseBill, PurchaseBillItem, ProductBatch, ProductBatchStock,
  StockLedger, User, Role,
} = require('../models');
const purchaseController = require('../controllers/purchaseController');

let pass = 0, fail = 0;
const results = [];
const FIXTURE_PREFIX = '_TBP_';

function check(name, condition, detail = '') {
  if (condition) { pass++; results.push(`  ✓ ${name}`); }
  else           { fail++; results.push(`  ✗ ${name}${detail ? ' — ' + detail : ''}`); }
}

// Mock res object that captures status + json body so we can assert on
// controller responses without going through Express.
function mockRes() {
  const r = { _status: 200, _body: null };
  r.status = (code) => { r._status = code; return r; };
  r.json   = (body) => { r._body = body;  return r; };
  return r;
}

async function cleanup() {
  // Tear down in FK-safe order. Bill numbers are auto-generated by the
  // controller (ignoring whatever the test passed in), so we anchor
  // cleanup on the test supplier + product names which use our prefix.
  const testProdSel = `(SELECT product_id FROM products WHERE product_name LIKE :p)`;
  const testSuppSel = `(SELECT party_id FROM parties WHERE party_name LIKE :p)`;
  const testBillSel = `(SELECT purchase_bill_id FROM purchase_bills WHERE supplier_id IN ${testSuppSel})`;

  await sequelize.query(`DELETE FROM stock_ledger WHERE product_id IN ${testProdSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM purchase_bill_items WHERE purchase_bill_id IN ${testBillSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM ledger_entries WHERE source_type IN ('purchase_bill','purchase_bill_payment') AND reference_id IN ${testBillSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM payment_splits WHERE transaction_id IN (SELECT transaction_id FROM payments_receipts WHERE party_id IN ${testSuppSel})`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM payments_receipts WHERE party_id IN ${testSuppSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM purchase_bills WHERE supplier_id IN ${testSuppSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM product_batch_stock WHERE product_id IN ${testProdSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM product_batches WHERE product_id IN ${testProdSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM product_godown_stock WHERE product_id IN ${testProdSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM products WHERE product_name LIKE :p`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM ledger_accounts WHERE party_id IN ${testSuppSel}`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`UPDATE parties SET ledger_account_id = NULL WHERE party_name LIKE :p`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM parties WHERE party_name LIKE :p`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
  await sequelize.query(`DELETE FROM categories WHERE category_name LIKE :p`,
    { replacements: { p: FIXTURE_PREFIX + '%' } });
}

async function setupFixtures() {
  // Find the seeded admin user — the controller writes created_by from
  // req.user.user_id, so we need a real user.
  const adminUser = await User.findOne({
    include: [{ model: Role }],
    where: { username: 'admin' },
  });
  if (!adminUser) throw new Error('Seeded admin user not found — run server once to seed.');

  // Default godown — same one the seeder creates.
  const godown = await Godown.findOne({ where: { is_default: true } });
  if (!godown) throw new Error('Default godown not found — run server once to seed.');

  // Test category + supplier + two products (one batch-tracked, one not)
  const cat = await Category.create({ category_name: FIXTURE_PREFIX + 'cat' });
  const supplier = await Party.create({
    party_name: FIXTURE_PREFIX + 'supplier',
    party_type: 'Supplier',
    mobile_1: '9000000001',
    is_active: true,
  });
  const batchProduct = await Product.create({
    barcode: FIXTURE_PREFIX + 'BATCH01',
    product_name: FIXTURE_PREFIX + 'Pharma Tablet 500mg',
    category_id: cat.category_id,
    purchase_rate: 10, sale_rate: 15, mrp: 18,
    is_batch_tracked: true,
    is_active: true,
  });
  // Second batch-tracked product to verify uniqueness scope (B-CREATE-4)
  const batchProduct2 = await Product.create({
    barcode: FIXTURE_PREFIX + 'BATCH02',
    product_name: FIXTURE_PREFIX + 'Different Drug 250mg',
    category_id: cat.category_id,
    purchase_rate: 5, sale_rate: 8, mrp: 10,
    is_batch_tracked: true,
    is_active: true,
  });

  // Ensure batch_tracking_enabled is ON so the validation pass actually runs.
  const settings = await SystemSettings.findByPk(1);
  await settings.update({ batch_tracking_enabled: true });

  return { adminUser, godown, cat, supplier, batchProduct, batchProduct2 };
}

function makeReq(adminUser) {
  return (body) => ({ body, user: adminUser, params: {} });
}

async function runTests() {
  await cleanup(); // wipe leftovers from prior runs
  const fix = await setupFixtures();
  const buildReq = makeReq(fix.adminUser);

  // ── B-CREATE-1: missing batch_number on a batch-tracked line ───────
  {
    const res = mockRes();
    await purchaseController.create(buildReq({
      bill_number: FIXTURE_PREFIX + 'BC1',
      bill_date: '2026-05-02',
      supplier_id: fix.supplier.party_id,
      godown_id: fix.godown.godown_id,
      items: [{
        product_id: fix.batchProduct.product_id,
        product_name: fix.batchProduct.product_name,
        barcode: fix.batchProduct.barcode,
        quantity: 100, purchase_rate: 10,
        // batch_number omitted on purpose
      }],
    }), res);
    check('B-CREATE-1: rejects batch-tracked line without batch_number',
      res._status === 400 && /batch[- ]?tracked/i.test(res._body?.error || ''),
      `status=${res._status} body=${JSON.stringify(res._body)}`);
  }

  // ── B-CREATE-2: new batch number creates batch + stock + ledger ────
  let batchAId = null;
  {
    const res = mockRes();
    await purchaseController.create(buildReq({
      bill_number: FIXTURE_PREFIX + 'BC2',
      bill_date: '2026-05-02',
      supplier_id: fix.supplier.party_id,
      godown_id: fix.godown.godown_id,
      items: [{
        product_id: fix.batchProduct.product_id,
        product_name: fix.batchProduct.product_name,
        barcode: fix.batchProduct.barcode,
        quantity: 100, purchase_rate: 10,
        batch_number: 'LOT-2401',
        manufacture_date: '2026-01-15',
        expiry_date: '2027-01-15',
      }],
    }), res);
    check('B-CREATE-2: 201 created on valid batch purchase',
      res._status === 201,
      `status=${res._status} body=${JSON.stringify(res._body)}`);

    const batch = await ProductBatch.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_number: 'LOT-2401' },
    });
    check('B-CREATE-2: ProductBatch row created with metadata',
      !!batch
        && batch.manufacture_date === '2026-01-15'
        && batch.expiry_date === '2027-01-15',
      `batch=${JSON.stringify(batch)}`);
    if (batch) batchAId = batch.batch_id;

    const stockRow = batch ? await ProductBatchStock.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batch.batch_id, godown_id: fix.godown.godown_id },
    }) : null;
    check('B-CREATE-2: ProductBatchStock holds the purchased qty',
      !!stockRow && parseFloat(stockRow.current_stock) === 100,
      `stockRow=${JSON.stringify(stockRow)}`);

    const ledgerRow = batch ? await StockLedger.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batch.batch_id, transaction_type: 'Purchase' },
    }) : null;
    check('B-CREATE-2: stock_ledger row carries batch_id',
      !!ledgerRow && parseFloat(ledgerRow.quantity_in) === 100,
      `ledgerRow=${JSON.stringify(ledgerRow)}`);

    const billItem = await PurchaseBillItem.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batch?.batch_id || -1 },
    });
    check('B-CREATE-2: PurchaseBillItem.batch_id is set on the line',
      !!billItem,
      `billItem=${JSON.stringify(billItem)}`);
  }

  // ── B-CREATE-3: same batch number again → no duplicate batch ──────
  let bill3Id = null;
  {
    const before = await ProductBatch.count({
      where: { product_id: fix.batchProduct.product_id, batch_number: 'LOT-2401' },
    });
    const res = mockRes();
    await purchaseController.create(buildReq({
      bill_date: '2026-05-03',
      supplier_id: fix.supplier.party_id,
      godown_id: fix.godown.godown_id,
      items: [{
        product_id: fix.batchProduct.product_id,
        product_name: fix.batchProduct.product_name,
        barcode: fix.batchProduct.barcode,
        quantity: 50, purchase_rate: 10,
        batch_number: 'LOT-2401',
      }],
    }), res);
    check('B-CREATE-3: 201 on re-purchase of same batch',
      res._status === 201,
      `status=${res._status} body=${JSON.stringify(res._body)}`);
    bill3Id = res._body?.purchase_bill_id;

    const after = await ProductBatch.count({
      where: { product_id: fix.batchProduct.product_id, batch_number: 'LOT-2401' },
    });
    check('B-CREATE-3: no duplicate batch row created',
      before === 1 && after === 1,
      `before=${before} after=${after}`);

    const stockRow = await ProductBatchStock.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batchAId, godown_id: fix.godown.godown_id },
    });
    check('B-CREATE-3: batch stock accumulates (100 + 50 = 150)',
      !!stockRow && parseFloat(stockRow.current_stock) === 150,
      `stockRow=${JSON.stringify(stockRow)}`);
  }

  // ── B-CREATE-4: same batch number on a different product is allowed ─
  {
    const res = mockRes();
    await purchaseController.create(buildReq({
      bill_number: FIXTURE_PREFIX + 'BC4',
      bill_date: '2026-05-03',
      supplier_id: fix.supplier.party_id,
      godown_id: fix.godown.godown_id,
      items: [{
        product_id: fix.batchProduct2.product_id,
        product_name: fix.batchProduct2.product_name,
        barcode: fix.batchProduct2.barcode,
        quantity: 25, purchase_rate: 5,
        batch_number: 'LOT-2401',
      }],
    }), res);
    check('B-CREATE-4: 201 on same batch number for different product',
      res._status === 201,
      `status=${res._status} body=${JSON.stringify(res._body)}`);
    const distinctBatches = await ProductBatch.findAll({
      where: { batch_number: 'LOT-2401' },
    });
    check('B-CREATE-4: two distinct ProductBatch rows exist for the shared name',
      distinctBatches.length === 2,
      `count=${distinctBatches.length}`);
  }

  // ── B-CANCEL: cancelling reverses batch stock ──────────────────────
  {
    const before = await ProductBatchStock.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batchAId, godown_id: fix.godown.godown_id },
    });
    const res = mockRes();
    await purchaseController.cancel({
      ...buildReq({ reason: 'test' }),
      params: { id: bill3Id },
    }, res);
    check('B-CANCEL: cancel returns success',
      (res._status === 200 || res._status === undefined) && !!res._body?.message,
      `status=${res._status} body=${JSON.stringify(res._body)}`);
    const after = await ProductBatchStock.findOne({
      where: { product_id: fix.batchProduct.product_id, batch_id: batchAId, godown_id: fix.godown.godown_id },
    });
    check('B-CANCEL: batch stock decremented by cancelled qty (150 → 100)',
      !!after && parseFloat(after.current_stock) === parseFloat(before.current_stock) - 50,
      `before=${before?.current_stock} after=${after?.current_stock}`);
  }

  // ── B-DISABLED: global toggle off → batch field silently dropped ───
  {
    await SystemSettings.update({ batch_tracking_enabled: false }, { where: { setting_id: 1 } });
    const res = mockRes();
    // A line for a batch-tracked product WITHOUT a batch number — should
    // succeed because the global toggle being off neutralises the rule.
    await purchaseController.create(buildReq({
      bill_number: FIXTURE_PREFIX + 'BCD',
      bill_date: '2026-05-04',
      supplier_id: fix.supplier.party_id,
      godown_id: fix.godown.godown_id,
      items: [{
        product_id: fix.batchProduct.product_id,
        product_name: fix.batchProduct.product_name,
        barcode: fix.batchProduct.barcode,
        quantity: 5, purchase_rate: 10,
      }],
    }), res);
    check('B-DISABLED: global OFF → no validation, bill saves',
      res._status === 201,
      `status=${res._status} body=${JSON.stringify(res._body)}`);
    // Restore the setting we toggled
    await SystemSettings.update({ batch_tracking_enabled: true }, { where: { setting_id: 1 } });
  }
}

async function main() {
  console.log('━━━ Purchase batch-tracking integration tests ━━━');
  try {
    await runTests();
  } catch (err) {
    fail++;
    results.push(`  ✗ Suite crashed: ${err.message}`);
    console.error(err);
  } finally {
    try { await cleanup(); } catch (e) { console.warn('cleanup warning:', e.message); }
    await sequelize.close();
  }
  console.log(results.join('\n'));
  console.log(`━━━ ${pass} passed, ${fail} failed ━━━`);
  process.exit(fail === 0 ? 0 : 1);
}

main();
